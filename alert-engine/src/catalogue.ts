// Every metric an alert rule can use, with the defaults the portal's rule library offers.
// This is the single source: the API serves it (GET /v1/alert-rules/metrics) and validates rules
// against it, and ruleEvaluator.ts computes each metric.

export type Operator = 'gt' | 'gte' | 'lt' | 'lte' | 'eq' | 'neq'
export type Severity = 'critical' | 'high' | 'medium' | 'low' | 'info'
export type Category = 'Identity' | 'Security' | 'Devices' | 'Endpoints' | 'Network' | 'Workloads' | 'Platform' | 'Custom'

export interface MetricDef {
  metric:      string
  label:       string
  category:    Category
  source:      'entra_id' | 'defender' | 'intune' | 'agent' | 'custom'
  description: string
  /** Counts events inside the rule's window */
  windowed:    boolean
  /** Per-item limit the metric applies before counting, e.g. "CPU above 90%" */
  param?:      { label: string; default: number; unit?: string }
  /** Unit of the metric value itself */
  unit?:       string
  /** What the affected list holds */
  affects:     'users' | 'devices' | 'items'
  defaults:    { name: string; operator: Operator; threshold: number; severity: Severity; window?: number; cooldown?: number }
  recommended: string
}

